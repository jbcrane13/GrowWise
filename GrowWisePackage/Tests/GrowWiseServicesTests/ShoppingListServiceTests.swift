@MainActor
struct ShoppingListServiceTests {
    // MARK: - Helpers

    private func makeService() -> ShoppingListService {
        ShoppingListService()
    }

    private func makeGarden(type: GardenType = .outdoor, soilType: SoilType = .loam, createdDaysAgo: Int = 30) -> Garden {
        let garden = Garden(name: "Test Garden", gardenType: type)
        garden.soilType = soilType
        garden.createdDate = Calendar.current.date(byAdding: .day, value: -createdDaysAgo, to: Date())
        return garden
    }

    private func makePlant(name: String = "Tomato", growthStage: GrowthStage? = .vegetative, lastFertilized: Date? = Date(), containerType: ContainerType? = .container) -> Plant {
        let plant = Plant(name: name, plantType: .vegetable)
        plant.growthStage = growthStage
        plant.lastFertilized = lastFertilized
        plant.containerType = containerType
        return plant
    }

    // MARK: - generateShoppingList overall

    @Test("generateShoppingList returns empty list for garden with no trigger conditions")
    func generateShoppingListReturnsEmptyForNoTriggers() {
        let service = makeService()
        // outdoor loam garden created 30 days ago, mature plants fertilized recently
        let garden = makeGarden(type: .outdoor, soilType: .loam, createdDaysAgo: 30)
        let plant = makePlant(growthStage: .mature, lastFertilized: Date(), containerType: .inGround)
        let items = service.generateShoppingList(for: garden, plants: [plant])
        #expect(items.isEmpty)
    }

    @Test("generateShoppingList returns items from multiple categories when multiple conditions are met")
    func generateShoppingListCombinesMultipleCategories() {
        let service = makeService()
        // new container garden (tools + containers + soil) with seedling needing seeds + no fertilizer
        let garden = makeGarden(type: .container, soilType: .loam, createdDaysAgo: 2)
        let plant = makePlant(growthStage: .seedling, lastFertilized: nil, containerType: nil)
        let items = service.generateShoppingList(for: garden, plants: [plant])
        let categories = Set(items.compactMap(\.category))
        #expect(categories.contains(.seeds))
        #expect(categories.contains(.soilAmendments))
        #expect(categories.contains(.fertilizer))
        #expect(categories.contains(.containers))
        #expect(categories.contains(.tools))
    }

    @Test("all generated items are marked as auto-generated")
    func generatedItemsAreMarkedAutoGenerated() {
        let service = makeService()
        let garden = makeGarden(type: .raised, soilType: .loam, createdDaysAgo: 3)
        let plant = makePlant(growthStage: .seed, lastFertilized: nil, containerType: nil)
        let items = service.generateShoppingList(for: garden, plants: [plant])
        #expect(!items.isEmpty)
        #expect(items.allSatisfy(\.isAutoGenerated))
    }

    @Test("all generated items have their garden set")
    func generatedItemsHaveGardenAssigned() {
        let service = makeService()
        let garden = makeGarden(type: .raised, soilType: .loam, createdDaysAgo: 3)
