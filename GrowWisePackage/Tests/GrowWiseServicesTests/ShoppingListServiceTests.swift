    // MARK: - togglePurchased

    @Test("togglePurchased flips unpurchased item to purchased")
    func togglePurchasedFlipsToTrue() {
        let service = makeService()
        let item = ShoppingItem(name: "Fertilizer", category: .fertilizer)
        #expect(item.isPurchased == false)
        service.togglePurchased(item)
        #expect(item.isPurchased == true)
    }

    @Test("togglePurchased flips purchased item back to unpurchased")
    func togglePurchasedFlipsBackToFalse() {
        let service = makeService()
        let item = ShoppingItem(name: "Fertilizer", category: .fertilizer)
        item.isPurchased = true
        service.togglePurchased(item)
        #expect(item.isPurchased == false)
    }

    @Test("toggling twice restores original purchased state")
    func togglePurchasedTwiceRestoresOriginalState() {
        let service = makeService()
        let item = ShoppingItem(name: "Seeds", category: .seeds)
        service.togglePurchased(item)
        service.togglePurchased(item)
        #expect(item.isPurchased == false)
    }

    @Test("toggling one item does not affect another item's purchased state")
    func togglePurchasedDoesNotAffectOtherItems() {
        let service = makeService()
        let item1 = ShoppingItem(name: "Seeds", category: .seeds)
        let item2 = ShoppingItem(name: "Tools", category: .tools)
        service.togglePurchased(item1)
        #expect(item1.isPurchased == true)
        #expect(item2.isPurchased == false)
    }
